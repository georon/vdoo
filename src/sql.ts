// A generic SQL script (CREATE TABLE with keys) for the schema. Types are written as entered.
import { type Schema, tableById } from "./model";

const q = (name: string) => `"${name.replace(/"/g, '""')}"`;

export function toSql(schema: Schema): string {
  const out: string[] = [`-- ${schema.name}, generated by vdoo`, ""];
  for (const table of schema.tables) {
    const lines = table.columns.map((c) => `  ${q(c.name)} ${c.type}${c.pk || !c.nullable ? " NOT NULL" : ""}${c.unique && !c.pk ? " UNIQUE" : ""}`);
    const pks = table.columns.filter((c) => c.pk);
    if (pks.length) lines.push(`  PRIMARY KEY (${pks.map((c) => q(c.name)).join(", ")})`);
    if (table.comment) out.push(`-- ${table.comment.replace(/\n/g, " ")}`);
    out.push(`CREATE TABLE ${q(table.name)} (`, lines.join(",\n"), ");", "");
  }
  for (const relation of schema.relations) {
    const parent = tableById(schema, relation.parent), child = tableById(schema, relation.child);
    if (!parent || !child || !relation.columns.length) continue;
    const pairs = relation.columns.map((p) => ({ fk: child.columns.find((c) => c.id === p.fk), ref: parent.columns.find((c) => c.id === p.ref) }))
      .filter((p) => p.fk && p.ref);
    if (!pairs.length) continue;
    out.push(`ALTER TABLE ${q(child.name)} ADD CONSTRAINT ${q(`fk_${child.name}_${parent.name}_${relation.id}`)}`,
      `  FOREIGN KEY (${pairs.map((p) => q(p.fk!.name)).join(", ")}) REFERENCES ${q(parent.name)} (${pairs.map((p) => q(p.ref!.name)).join(", ")});`, "");
  }
  return out.join("\n");
}
